using Microsoft.ClearScript;

namespace Cs2Ts.Runtime;

/// <summary>
/// What every entity's wide surface derives from: the fields, and nothing else.
///
/// It exists for one reason, and it is a reason that only shows up in a test.
/// <see cref="DefaultScriptUsageAttribute"/> governs the members a type <em>declares</em>,
/// not the ones it inherits, so a host class that opts out and then does not override
/// <c>Equals</c>, <c>GetHashCode</c> and <c>ToString</c> hands all three to script
/// anyway. Nothing dangerous comes of it — reflection is prohibited separately — but the
/// surface an author sees is meant to be exactly the fields, and three of
/// <see cref="object"/>'s members turning up among them is how that stops being true.
///
/// Declaring the overrides here settles it once. The alternative is three lines of
/// boilerplate at the top of every entity surface, and those surfaces are about to be
/// generated by the hundred — a rule that has to be re-applied per class is a rule that
/// will be missed.
///
/// The behaviour is unchanged: reference equality, which is already the right answer,
/// because one surface is made per entity and kept.
/// </summary>
[DefaultScriptUsage(ScriptAccess.None)]
public abstract class RawSurface
{
    /// <inheritdoc />
    public override bool Equals(object? obj) => base.Equals(obj);

    /// <inheritdoc />
    public override int GetHashCode() => base.GetHashCode();

    /// <summary>
    /// The type's name. What a script gets from <c>entity</c> rather than
    /// <c>entity.raw</c> is the readable one; this is here to be hidden, not to be read.
    /// </summary>
    public override string ToString() => GetType().Name;
}
